const DICT: Record<Lang, Record<I18nKey, string>> = { es: ES, en: EN };

/** El texto de una clave. Si una clave dinámica no existe, devuelve la clave. */
export function tr(lang: Lang, key: I18nKey | string): string {
  return (DICT[lang] as Record<string, string>)[key] ?? (ES as Record<string, string>)[key] ?? key;
}

/**
 * v0.48 — `tr` con huecos: `trf(lang, "home.players", { n: 12 })` → «12 jugadores».
 * Un hueco que no llega se deja tal cual (`{n}`), para que se vea en pantalla
 * y no pase desapercibido.
 */
export function trf(lang: Lang, key: I18nKey, vars: Record<string, string | number>): string {
  return tr(lang, key).replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/**
 * v0.48 — un ordinal: «3.º» en español, «3rd» en inglés (11th, 12th y 13th
 * son la excepción a la regla de la última cifra).
 */
export function ordinal(lang: Lang, n: number): string {
  if (lang === "es") return `${n}.º`;
  const d = n % 100;
  if (d >= 11 && d <= 13) return `${n}th`;
  return `${n}${["th", "st", "nd", "rd"][n % 10] ?? "th"}`;
}

/** v0.48 — «en 3 días», «hoy»… en el idioma pedido. */
export function diasRelativos(lang: Lang, n: number): string {
  if (n === 0) return tr(lang, "rel.today");
  if (n === 1) return tr(lang, "rel.tomorrow");
  if (n === -1) return tr(lang, "rel.yesterday");
  return n > 0 ? trf(lang, "rel.inDays", { n }) : trf(lang, "rel.daysAgo", { n: Math.abs(n) });
}

